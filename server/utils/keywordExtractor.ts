export const extractKeywords = (text: string): string[] => {
  if (!text) return [];
  return text.toLowerCase().match(/\b[a-z]{3,}\b/g) || [];
};

export const extractDomainKeywords = (text: string): string[] => {
  const raw = extractKeywords(text);
  const filtered = raw.filter((word) => !STOP_WORDS.has(word));
  return [...new Set(filtered)];
};
